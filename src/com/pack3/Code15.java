package com.pack3;


public class Code15 {
    public static void main(String[] args) {

        // Binary literal
    	// Primitive data type int is used for the print the binary number as the int value
        int binary = 0b1010;

        // Octal literal
        // int also used to convert octal into teh int value
        int octal = 01234;

        // Hexadecimal literal
        // and for the int used for the also conver hexadecimal inot to the int value
        int hexadecimal = 0x1A;

        // Print the values
        System.out.println("Binary Literal (0b1010) as decimal: " + binary);
        System.out.println("Octal Literal (01234) as decimal: " + octal);
        System.out.println("Hexadecimal Literal (0x1A) as decimal: " + hexadecimal);
    }
}