package com.pack3;

public class Code16 {
    public static void main(String[] args) {

        //Decimal literal
        int literal=200;

        // Octal literal
        int literal1=020;

        //Hexadecimal literal
        int literal2=0xAB;

        // double literal
        float literal3=1.2345f;

        // float literal
        float literal4=7.25f;

        // Character literal
        char literal5='K';

        // Print the value 
        System.out.println("Decimal: "+literal);
        System.out.println("Octal: "+literal1);
        System.out.println("Hex: "+literal2);
        System.out.println("Double: "+literal3);
        System.out.println("Float: "+literal4);
        System.out.println("Char: "+literal5);
        
    }
}
